"""Sanitized agent blackboard: only controlled words/numbers, never source text."""
from __future__ import annotations

from .jev import fingerprint
from .policy import MODEL, REVIEW_THRESHOLD


def render(shadow: dict | None = None, evaluation: dict | None = None) -> str:
    shadow, evaluation = shadow or {}, evaluation or {}
    lines = (shadow.get('lines', 0) - shadow.get('unmeasured_or_error', 0)) if shadow.get('mode') == 'live' else 0
    samples = evaluation.get('samples', 0)
    if type(lines) is not int or type(samples) is not int or min(lines, samples) < 0:
        raise ValueError('Invalid news counts')
    eligible = evaluation.get('eligible_for_additive_routing') is True and evaluation.get('policy') == fingerprint()
    state = 'Eligible for independent promotion review; STILL SHADOW' if eligible else 'SHADOW — not graduated'
    return f'''# Agent routing news

<!-- Generated by tools.public_release.news; no source text or private paths. -->

## Release routing boundary

Private-source pushes may refresh `release-private` inside a verified private
repository. Failures keep the previous stage. **Public updates require an explicit
user request** and separate independent review; private staging is not approval.
No automatic live classifier calls, model promotion or repository visibility changes.

## Private-to-public line screening

**Status: {state}.** Jev has **no publication, edit, shell, commit or push authority**.

- Sensor: `{MODEL}`; policy fingerprint `{fingerprint()}`.
- Inputs: every text line in deterministic path/line order, with adjacent context.
  Credential-shaped documents and oversize lines are withheld and sent to review.
- Judgments: name/handle, telephone, private-machine details, other private facts.
  Email addresses are intentionally allowed; that can permit identity correlation.
- Any probability >= {REVIEW_THRESHOLD} is a **would-route** to Luna/reviewer.
  Lower probabilities do not clear deterministic findings. Errors are review, not no.
- Luna: `openai-codex/gpt-6-luna`, thinking `max`, no tools; hash-pinned,
  numbered-line proposals only. Independent review, rescan and tests precede use.
- Live classifier lines measured: {lines}. Independently measured held-out samples: {samples}.
- No 99% accuracy claim is made by offline/mock tests or by a model's probability.
- Graduation: >=500 deduplicated nontrivial held-out samples, >=300 positives per
  risk category, one-sided 95% Wilson lower bounds >=99% for accuracy and per-risk
  recall, zero missed positive lines, no missing/error/mock/stale evidence. Freeze
  policy/model; new policy invalidates evidence. Independent promotion is manual.

Deterministic privacy/secret checks and final Git/media review remain mandatory
regardless of graduation. Read [the release workflow](RELEASE.md) before exporting.
'''
