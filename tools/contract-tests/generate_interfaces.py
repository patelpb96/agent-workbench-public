"""Deterministically generate shared Rust/TS wire types from the canonical schema.

No network/model call. Rust formatting uses the installed project Rust toolchain.
Semantic/native admission rules are separately implemented and tested.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / 'contracts/execution.schema.json'
RUST = ROOT / 'src-tauri/src/execution/generated.rs'
TS = ROOT / 'frontend/src/execution/generated.ts'


def pascal(name):
    return ''.join(word.capitalize() for word in re.split(r'[^A-Za-z0-9]+', name) if word)


def rust_type(spec):
    if '$ref' in spec:
        return pascal(spec['$ref'].split('/')[-1])
    if 'anyOf' in spec:
        options = [item for item in spec['anyOf'] if item.get('type') != 'null']
        if len(options) != 1:
            raise ValueError('Only nullable union fields are supported.')
        return f'Option<{rust_type(options[0])}>'
    if 'const' in spec:
        if isinstance(spec['const'], bool):
            return 'bool'
        return 'u64' if isinstance(spec['const'], int) else 'String'
    if 'enum' in spec:
        return 'String'
    return {'string': 'String', 'integer': 'u64', 'number': 'f64', 'boolean': 'bool',
            'array': f"Vec<{rust_type(spec['items'])}>" if spec.get('type') == 'array' else ''}[spec['type']]


def is_copy(spec, definitions):
    """Whether the Rust type for `spec` is Copy (numbers, booleans, the generated enums, and nullable ones of those):
    such fields are copied with `*field`, not `.clone()` (clippy's clone_on_copy)."""
    if '$ref' in spec:
        target = definitions.get(spec['$ref'].split('/')[-1], {})
        # A generated enum, or an alias of a number (`pub type Sequence = u64;`).
        return 'enum' in target or (target.get('type') in ('integer', 'number', 'boolean') and 'properties' not in target)
    if 'anyOf' in spec:
        options = [item for item in spec['anyOf'] if item.get('type') != 'null']
        return len(options) == 1 and is_copy(options[0], definitions)
    return rust_type(spec) in ('u64', 'f64', 'bool')


def ts_type(spec):
    if '$ref' in spec:
        return pascal(spec['$ref'].split('/')[-1])
    if 'anyOf' in spec:
        return ' | '.join('null' if item.get('type') == 'null' else ts_type(item) for item in spec['anyOf'])
    if 'const' in spec:
        return json.dumps(spec['const'])
    if 'enum' in spec:
        return ' | '.join(json.dumps(item) for item in spec['enum'])
    if spec['type'] == 'array':
        return f'Array<{ts_type(spec["items"])}>'
    return {'string':'string', 'integer':'number', 'number':'number', 'boolean':'boolean'}[spec['type']]


def enum_rust(name, values):
    lines = ['#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]', f'pub enum {name} {{']
    for value in values:
        lines += [f'    #[serde(rename = {json.dumps(value)})]', f'    {pascal(value)},']
    lines += ['}', f'impl {name} {{', "    pub fn as_str(self) -> &'static str {", '        match self {']
    lines += [f'            Self::{pascal(value)} => {json.dumps(value)},' for value in values]
    return lines + ['        }', '    }', '}']


def generate(schema):
    definitions = schema['$defs']
    rs = ['// @generated by tools/contract-tests/generate_interfaces.py; DO NOT EDIT.', 'use serde::{Deserialize, Serialize};', '', "fn required_option<'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error>", "where D: serde::Deserializer<'de>, T: Deserialize<'de> {", '    Option::<T>::deserialize(deserializer)', '}', '']
    ts = ['// @generated by tools/contract-tests/generate_interfaces.py; DO NOT EDIT.', '']
    for name, spec in definitions.items():
        if name == 'run_event':
            continue
        typ = pascal(name)
        if 'enum' in spec:
            rs += enum_rust(typ, spec['enum']) + ['']
            ts += [f'export type {typ} = {ts_type(spec)};', '']
        elif spec.get('type') == 'object':
            rs += ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]', '#[serde(deny_unknown_fields)]', f'pub struct {typ} {{']
            ts += [f'export interface {typ} {{']
            required = set(spec.get('required', []))
            for field, field_spec in spec['properties'].items():
                rtype = rust_type(field_spec)
                if field not in required:
                    rtype = f'Option<{rtype}>'
                if field in required and rtype.startswith('Option<'):
                    rs += ['    #[serde(deserialize_with = "required_option")]']
                if field not in required:
                    # Absent optional fields keep canonical bytes of older requests/receipts unchanged.
                    rs += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
                rs += [f'    pub {field}: {rtype},']
                ts += [f'  {field}{"" if field in required else "?"}: {ts_type(field_spec)};']
            rs += ['}', '']; ts += ['}', '']
        else:
            rs += [f'pub type {typ} = {rust_type(spec)};', '']
            ts += [f'export type {typ} = {ts_type(spec)};', '']

    header = definitions['event_header']['properties']
    variants = schema['x-event-variants']
    rs += ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]', '#[serde(tag = "kind", deny_unknown_fields)]', 'pub enum RunEvent {']
    ts += ['export type RunEvent =']
    for kind, payload in variants.items():
        rs += [f'    #[serde(rename = "{kind}")]', f'    {pascal(kind)} {{']
        rs += [f'        {field}: {rust_type(spec)},' for field, spec in header.items()]
        rs += [f'        payload: {pascal(payload)},', '    },']
        ts += [f'  | (EventHeader & {{ kind: "{kind}"; payload: {pascal(payload)} }})']
    rs += ['}', '', '#[derive(Debug, Clone, PartialEq)]', 'pub enum EventPayload {']
    rs += [f'    {pascal(kind)}({pascal(payload)}),' for kind, payload in variants.items()]
    rs += ['}', '', 'impl RunEvent {', '    pub fn from_parts(header: EventHeader, payload: EventPayload) -> Self {', '        match payload {']
    for kind in variants:
        rs += [f'            EventPayload::{pascal(kind)}(payload) => Self::{pascal(kind)} {{']
        rs += [f'                {field}: header.{field},' for field in header]
        rs += ['                payload,', '            },']
    rs += ['        }', '    }', '    pub fn header(&self) -> EventHeader {', '        match self {']
    fields = ', '.join(header)
    for kind in variants:
        rs += [f'            Self::{pascal(kind)} {{ {fields}, .. }} => EventHeader {{']
        rs += [f'                {field}: *{field},' if is_copy(spec, definitions) else f'                {field}: {field}.clone(),' for field, spec in header.items()]
        rs += ['            },']
    rs += ['        }', '    }', "    pub fn kind(&self) -> &'static str {", '        match self {']
    rs += [f'            Self::{pascal(kind)} {{ .. }} => "{kind}",' for kind in variants]
    rs += ['        }', '    }', '}', '', 'impl RunState {', '    pub fn can_transition_to(self, next: Self) -> bool {', '        match self {']
    for state, targets in schema['x-run-transitions'].items():
        expr = 'matches!(next, ' + ' | '.join(f'Self::{pascal(target)}' for target in targets) + ')' if targets else 'false'
        rs += [f'            Self::{pascal(state)} => {expr},']
    rs += ['        }', '    }', '}', '']
    ts[-len(variants):] = [line + (';' if index == len(variants)-1 else '') for index, line in enumerate(ts[-len(variants):])]
    ts += ['', 'export const runTransitions: Readonly<Record<RunState, ReadonlyArray<RunState>>> = '+json.dumps(schema['x-run-transitions'], indent=2)+';', '']
    for name, value in schema['x-limits'].items():
        rs += [f'pub const {name.upper()}: usize = {value};']
    rs += [f'pub const EXECUTION_NOTIFICATION: &str = "{schema["x-notification"]}";']
    ts += ['export const limits = '+json.dumps(schema['x-limits'], indent=2)+' as const;', f'export const executionNotification = "{schema["x-notification"]}" as const;', '']
    return '\n'.join(rs)+'\n', '\n'.join(ts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rustfmt = shutil.which('rustfmt') or str(Path.home()/'.cargo/bin/rustfmt.exe')
    outputs = []
    for schema, rust, typescript in [
        (SCHEMA, RUST, TS),
        (ROOT / 'contracts/execution-v2.schema.json',
         ROOT / 'src-tauri/src/execution_v2/generated.rs',
         ROOT / 'frontend/src/execution-v2/generated.ts'),
    ]:
        rs, ts = generate(json.loads(schema.read_text(encoding='utf-8')))
        rs = subprocess.run([rustfmt, '--edition', '2021', '--emit', 'stdout'], input=rs, capture_output=True, text=True, check=True).stdout
        outputs.extend([(rust, rs), (typescript, ts)])
    drift = []
    for path, content in outputs:
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open('w', encoding='utf-8', newline='\n') as output:
                output.write(content)
    if drift:
        print('Generated interface drift: '+', '.join(drift)); return 1
    print('Checked generated interfaces.' if args.check else 'Generated Rust and TypeScript interfaces.')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
